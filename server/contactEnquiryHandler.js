import crypto from 'node:crypto';
import { createClient as createSupabaseClient } from '@supabase/supabase-js';
import { getSupabaseServerKey } from './supabaseServerKey.js';
import { requireAdminUser } from './adminAuth.js';
import { validateEmailVerificationToken, sendSubmissionConfirmationEmail } from './emailOtpService.js';
import { sendStatusUpdateNotification } from './statusNotificationService.js';

class ContactEnquiryError extends Error {
  constructor(status, message) {
    super(message);
    this.status = status;
  }
}

function getServerClient(env, createClient) {
  const url = env.SUPABASE_URL || env.VITE_SUPABASE_URL;
  const key = getSupabaseServerKey(env);
  if (!url || !key) {
    throw new ContactEnquiryError(503, 'Server configuration is incomplete. Contact support.');
  }
  return (createClient || createSupabaseClient)(url, key);
}

const CONTACT_STATUSES = new Set([
  'Submitted',
  'Under Review',
  'Additional Information Required',
  'Verification Pending',
  'On Hold',
  'Completed',
  'Enquiry Completed',
  'Closed',
  'Rejected',
  'Contacted',
]);

/**
 * Submit a contact/callback enquiry from the public Contact form.
 * No authentication required — anyone may submit.
 * Does not store passwords, OTPs, or sensitive credentials.
 */
export async function handleContactEnquiry(
  reqBody,
  requestHeaders = {},
  { env = process.env, createClient } = {}
) {
  if (!reqBody || typeof reqBody !== 'object' || Array.isArray(reqBody)) {
    throw new ContactEnquiryError(400, 'Invalid request body.');
  }

  const { fullName, phone, email, serviceInterest, message, consent } = reqBody;

  // Validate required fields
  if (typeof fullName !== 'string' || fullName.trim().length < 2 || fullName.trim().length > 150) {
    throw new ContactEnquiryError(400, 'Please provide a valid full name (2–150 characters).');
  }
  if (typeof phone !== 'string' || phone.trim().length < 7 || phone.trim().length > 32) {
    throw new ContactEnquiryError(400, 'Please provide a valid phone number.');
  }
  if (!email || typeof email !== 'string' || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(email).trim())) {
    throw new ContactEnquiryError(400, 'Please provide a valid Gmail / email address.');
  }

  let verifiedEmail = null;
  let emailVerifiedAt = null;
  if (reqBody.emailVerificationToken) {
    const tokenCheck = validateEmailVerificationToken({
      email: email.trim().toLowerCase(),
      token: reqBody.emailVerificationToken,
      userId: null,
      env,
    });
    if (!tokenCheck.valid) {
      throw new ContactEnquiryError(400, tokenCheck.error || 'Your Gmail / email address must be verified with OTP before submitting.');
    }
    verifiedEmail = tokenCheck.email;
    emailVerifiedAt = tokenCheck.verifiedAt;
  }
  if (!consent) {
    throw new ContactEnquiryError(400, 'Consent to contact is required before submitting this form.');
  }
  if (message != null && typeof message === 'string' && message.length > 2000) {
    throw new ContactEnquiryError(400, 'Message must be 2000 characters or fewer.');
  }
  if (serviceInterest != null && typeof serviceInterest === 'string' && serviceInterest.length > 200) {
    throw new ContactEnquiryError(400, 'Service interest field is too long.');
  }

  // Resolve optional authenticated user
  const authorization = requestHeaders.authorization || requestHeaders.Authorization || '';
  const bearerMatch = /^Bearer\s+([^\s]+)$/i.exec(authorization);
  let userId = null;
  if (bearerMatch) {
    const client = getServerClient(env, createClient);
    const { data: userData } = await client.auth.getUser(bearerMatch[1]);
    userId = userData?.user?.id ?? null;
  }

  // Generate tracking ID
  const trackingId = `MAI-CON-${new Date().getFullYear()}-${crypto.randomBytes(4).toString('hex').toUpperCase()}`;

  const record = {
    full_name: fullName.trim(),
    phone: phone.trim(),
    email: email.trim().toLowerCase(),
    ...(verifiedEmail ? { verified_email: verifiedEmail } : {}),
    ...(emailVerifiedAt ? { email_verified_at: emailVerifiedAt } : {}),
    service_interest: serviceInterest?.trim() || null,
    message: message?.trim() || null,
    consent: Boolean(consent),
    status: 'Submitted',
    ...(userId ? { user_id: userId } : {}),
    // id column auto-generated by DB default
  };

  const client = getServerClient(env, createClient);
  const { data, error } = await client
    .from('contact_enquiries')
    .insert(record)
    .select('id, created_at')
    .single();

  if (error || !data?.id) {
    console.error('[contact-enquiry] persistence failed', { code: error?.code || 'unknown' });
    throw new ContactEnquiryError(503, 'The enquiry could not be saved. Please try again or contact us directly.');
  }

  const applicantEmail = verifiedEmail || email.trim();
  if (applicantEmail) {
    sendSubmissionConfirmationEmail({
      to: applicantEmail,
      fullName: fullName.trim() || 'Valued Client',
      formType: 'Consultation & Service Request',
      trackingId: data.id || trackingId,
      submittedAt: data.created_at || new Date().toISOString(),
      details: {
        'Service Interest': serviceInterest || 'General Advisory',
        'Phone': phone || undefined,
      },
      env,
    }).catch((err) => console.warn('[contact-enquiry] confirmation email notice:', err.message));
  }

  return {
    success: true,
    message: 'Your consultation request has been received.',
    trackingId: data.id,
    submittedAt: data.created_at,
  };
}

/**
 * Update status and admin notes for a contact enquiry.
 * Requires admin session cookie.
 */
export async function handleUpdateContactEnquiry(
  reqBody,
  requestHeaders = {},
  { env = process.env, createClient, requireAdmin = requireAdminUser } = {}
) {
  await requireAdmin(requestHeaders, { env });

  const { id, status, adminNotes } = reqBody || {};
  if (!id || typeof id !== 'string') {
    throw new ContactEnquiryError(400, 'Enquiry ID is required.');
  }
  if (status && !CONTACT_STATUSES.has(status)) {
    throw new ContactEnquiryError(400, `Invalid status. Must be one of: ${[...CONTACT_STATUSES].join(', ')}`);
  }

  const updatePayload = { updated_at: new Date().toISOString() };
  if (status) updatePayload.status = status;
  if (adminNotes !== undefined) updatePayload.admin_notes = adminNotes;

  const client = getServerClient(env, createClient);

  let current = null;
  // Record status history if status is changing
  if (status) {
    try {
      const { data } = await client
        .from('contact_enquiries')
        .select('status, email, full_name')
        .eq('id', id)
        .single();
      current = data;
    } catch (_) {}

    if (current && current.status !== status) {
      await client.from('submission_status_history').insert({
        form_type: 'contact',
        submission_id: id,
        previous_status: current.status,
        new_status: status,
        admin_notes: adminNotes || null,
        changed_by: 'admin',
      });
    }
  }

  const { error } = await client
    .from('contact_enquiries')
    .update(updatePayload)
    .eq('id', id);

  if (error) {
    console.error('[contact-enquiry] status update failed', { code: error?.code });
    throw new ContactEnquiryError(503, 'Status update failed. Please try again.');
  }

  let emailNotification = null;
  if (current?.email && status) {
    try {
      emailNotification = await sendStatusUpdateNotification({
        applicationId: id,
        customerEmail: current.email,
        customerName: current.full_name || 'Enquiry Customer',
        formType: 'contact',
        formTypeLabel: 'Service / Contact Enquiry',
        previousStatus: current?.status || 'Submitted',
        newStatus: status,
        adminRemark: adminNotes,
        env,
        createClient,
        forceResend: true,
      });
    } catch (emailErr) {
      emailNotification = { success: false, deliveryStatus: 'failed', error: emailErr.message };
    }
  }

  return { success: true, message: 'Contact enquiry updated.', id, status, emailNotification };
}

